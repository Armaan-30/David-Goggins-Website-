import { chromium, expect } from '@playwright/test';
import fs from 'node:fs/promises';
await fs.mkdir('qa',{recursive:true});
const browser=await chromium.launch({headless:true});
const errors=[];
for(const [name,width,height] of [['desktop',1440,900],['mobile',390,844],['tablet',768,1024]]){
 const page=await browser.newPage({viewport:{width,height},deviceScaleFactor:1});
 page.on('pageerror',e=>errors.push(`${name}: ${e.message}`));
 await page.goto('http://127.0.0.1:3000',{waitUntil:'networkidle'});
 await page.waitForTimeout(2000);
 await page.screenshot({path:`qa/${name}-hero.png`});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1))throw new Error(`${name}: horizontal overflow`);
 await page.getByRole('button',{name:'Open menu',exact:true}).click();
 await page.getByRole('dialog').waitFor({state:'visible'});
 await page.keyboard.press('Escape');
 await page.getByRole('dialog').waitFor({state:'hidden'});
 await page.getByRole('button',{name:'Open menu',exact:true}).click();
 await page.locator('.menu-link[href="#grind"]').click();
 await page.waitForTimeout(500);
 await page.getByRole('button',{name:/Discipline02/}).click();
 if(await page.locator('.story-card').count()!==2)throw new Error('Filter failed');
 await page.locator('.story-card').first().click();
 await page.locator('.detail-dialog').waitFor({state:'visible'});
 await page.getByRole('button',{name:'NEXT →',exact:true}).click();
 await page.keyboard.press('Escape');
 await page.locator('.detail-dialog').waitFor({state:'hidden'});
 await page.getByRole('button',{name:/All08/}).click();
 await page.getByRole('tab',{name:'2013'}).click();
 await expect(page.locator('#milestone-2')).toContainText('4,030');
 await page.keyboard.press('ArrowRight');
 await expect(page.getByRole('tab',{name:'2018'})).toHaveAttribute('aria-selected','true');
 await page.locator('#books').scrollIntoViewIfNeeded();await page.waitForTimeout(1000);
 await page.screenshot({path:`qa/${name}-books.png`});
 await page.locator('#grind').scrollIntoViewIfNeeded();await page.waitForTimeout(1000);
 await page.screenshot({path:`qa/${name}-gallery.png`});
 await page.close();
}
const reduced=await browser.newPage({viewport:{width:390,height:844},reducedMotion:'reduce'});
await reduced.goto('http://127.0.0.1:3000',{waitUntil:'networkidle'});
await expect(reduced.locator('.hero-reveal-toggle')).toHaveCount(0);
await reduced.screenshot({path:'qa/reduced-motion.png'});
await browser.close();
if(errors.length)throw new Error(errors.join('\n'));
console.log('PASS: desktop, mobile, tablet; overflow, navigation, Escape, filters, details, timeline keyboard, reduced-motion tap reveal.');
